from odoo import api, fields, models
from odoo.exceptions import UserError


class SaleOrder(models.Model):
    _inherit = 'sale.order'

    sn_is_toll = fields.Boolean(
        string='Toll Manufacturing',
        help='The order processes material supplied by the customer: the '
             'sold price is the processing fee, the finished goods stay the '
             'property of the customer and the supplied material is received '
             'through consignment receipts.',
    )
    sn_toll_order_ids = fields.One2many(
        'sn.toll.order', 'sale_order_id',
        string='Toll Manufacturing Orders', copy=False,
    )
    sn_toll_order_count = fields.Integer(
        string='Toll Order Count', compute='_compute_sn_toll_order_count',
    )

    @api.depends('sn_toll_order_ids')
    def _compute_sn_toll_order_count(self):
        for order in self:
            order.sn_toll_order_count = len(order.sn_toll_order_ids)

    def action_confirm(self):
        # Check before the confirmation so a misconfigured toll order does not
        # end up confirmed without its manufacturing order.
        for order in self.filtered('sn_is_toll'):
            if not order.order_line.filtered(
                    lambda line: not line.display_type
                    and line.product_id.is_storable):
                raise UserError(self.env._(
                    "Toll manufacturing order '%s' must contain at least one "
                    "storable finished product line.", order.display_name))
        result = super().action_confirm()
        self.filtered('sn_is_toll')._sn_create_toll_orders()
        return result

    def _sn_create_toll_orders(self):
        """Create one toll manufacturing order per storable line and attach
        the manufacturing order and the delivery generated by the sale."""
        toll_order_model = self.env['sn.toll.order']
        for order in self:
            lines = order.order_line.filtered(
                lambda line: not line.display_type
                and line.product_id.is_storable)
            if not lines:
                raise UserError(self.env._(
                    "Toll manufacturing order '%s' must contain at least one "
                    "storable finished product line.", order.display_name))
            for line in lines:
                toll_order = line.sn_toll_order_id
                if not toll_order:
                    bom = self.env['mrp.bom']._bom_find(
                        line.product_id, company_id=order.company_id.id,
                        bom_type='normal').get(line.product_id)
                    toll_order = toll_order_model.create({
                        'partner_id': order.partner_id.id,
                        'company_id': order.company_id.id,
                        'date_order': order.date_order,
                        'date_deadline': (
                            order.commitment_date.date()
                            if order.commitment_date else False),
                        'product_id': line.product_id.id,
                        'product_qty': line.product_uom_qty,
                        'bom_id': bom.id if bom else False,
                        'pricing_method': 'fixed',
                        'fee_unit': line.price_unit,
                        'state': 'confirmed',
                        'sale_order_id': order.id,
                        'sale_line_id': line.id,
                    })
                    line.sn_toll_order_id = toll_order.id
                productions = self.env['mrp.production'].search([
                    ('sale_line_id', '=', line.id)])
                if productions:
                    productions.write({
                        'sn_toll_order_id': toll_order.id,
                        'sn_toll_partner_id': order.partner_id.id,
                    })
                elif toll_order.bom_id:
                    # A make-to-stock sale does not launch the manufacturing
                    # order by itself: create it as a draft so the shop floor
                    # schedules it through the usual flow.
                    self.env['mrp.production'].create({
                        'product_id': line.product_id.id,
                        'product_qty': line.product_uom_qty,
                        'bom_id': toll_order.bom_id.id,
                        'picking_type_id': order.warehouse_id.manu_type_id.id,
                        'company_id': order.company_id.id,
                        'sale_line_id': line.id,
                        'sn_toll_order_id': toll_order.id,
                        'sn_toll_partner_id': order.partner_id.id,
                    })
                pickings = (
                    line.move_ids.picking_id
                    | line.move_ids.move_dest_ids.picking_id)
                for picking in pickings:
                    picking.write({
                        'sn_toll_order_id': toll_order.id,
                        'owner_id': order.partner_id.id,
                        'sn_toll_delivery':
                            picking.picking_type_id.code == 'outgoing',
                        'sn_toll_receipt':
                            picking.picking_type_id.code == 'incoming',
                    })
        return True

    def action_view_sn_toll_orders(self):
        self.ensure_one()
        action = self.env['ir.actions.act_window']._for_xml_id(
            'sn_wsd_toll.action_sn_toll_order')
        action['domain'] = [('sale_order_id', '=', self.id)]
        action['context'] = {
            'default_sale_order_id': self.id,
            'default_partner_id': self.partner_id.id,
        }
        if self.sn_toll_order_count == 1:
            action.update({
                'res_id': self.sn_toll_order_ids.id,
                'view_mode': 'form',
                'views': [(False, 'form')],
            })
        return action

    def action_create_sn_toll_orders(self):
        self.ensure_one()
        if self.state not in ('sale', 'done'):
            raise UserError(self.env._(
                "Confirm sale order '%s' before creating its toll "
                "manufacturing orders.", self.display_name))
        self._sn_create_toll_orders()
        return self.action_view_sn_toll_orders()


class SaleOrderLine(models.Model):
    _inherit = 'sale.order.line'

    sn_toll_order_id = fields.Many2one(
        'sn.toll.order', string='Toll Manufacturing Order', copy=False,
        index=True, check_company=True,
    )
