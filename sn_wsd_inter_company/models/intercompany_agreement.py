from odoo import SUPERUSER_ID, _, api, fields, models
from odoo.exceptions import ValidationError

LINK_LEVEL_SELECTION = [
    ('create_only', 'Create Only'),
    ('create_update', 'Create and Update'),
    ('create_update_cancel', 'Create, Update and Cancel'),
]

DOC_SCOPE_SELECTION = [
    ('so_po', 'Sale and Purchase Orders'),
    ('so_po_invoice', 'Orders and Invoices'),
    ('so_po_invoice_stock', 'Orders, Invoices and Transfers'),
]

PRICE_POLICY_SELECTION = [
    ('copy', 'Copy the Source Price'),
    ('pricelist', 'Recompute with the Target Price List'),
    ('cost_markup', 'Target Cost plus Markup'),
]

CONFLICT_POLICY_SELECTION = [
    ('source_wins', 'The Modified Document Wins'),
    ('latest_wins', 'The Most Recently Modified Wins'),
    ('manual', 'Leave the Decision to a User'),
]

AGREEMENT_STATE_SELECTION = [
    ('draft', 'Draft'),
    ('running', 'Running'),
    ('suspended', 'Suspended'),
    ('closed', 'Closed'),
]


class SnIntercompanyAgreement(models.Model):
    """Trade agreement between two companies of the database.

    One record holds both directions, so two companies selling to each other
    share a single contract: ``company_a`` is always the company with the
    lower id, which makes the pair unique and the direction of any document
    deterministic.
    """

    _name = 'sn.intercompany.agreement'
    _description = 'Inter-Company Trade Agreement'
    _inherit = ['mail.thread']
    _order = 'name, id'
    _rec_name = 'name'

    name = fields.Char(required=True, default='New', tracking=True)
    active = fields.Boolean(default=True, tracking=True)
    state = fields.Selection(
        AGREEMENT_STATE_SELECTION,
        string='Status',
        default='draft',
        required=True,
        tracking=True,
    )
    company_a_id = fields.Many2one(
        'res.company', string='Company A', required=True, index=True,
        ondelete='cascade')
    company_b_id = fields.Many2one(
        'res.company', string='Company B', required=True, index=True,
        ondelete='cascade')
    a_sells_to_b = fields.Boolean(
        string='Company A Sells to Company B', default=True,
        help="When set, a confirmed sale order of company A generates the "
             "matching purchase order in company B.")
    b_sells_to_a = fields.Boolean(
        string='Company B Sells to Company A', default=True,
        help="When set, a confirmed sale order of company B generates the "
             "matching purchase order in company A.")
    doc_scope = fields.Selection(
        DOC_SCOPE_SELECTION,
        string='Documents in Scope',
        default='so_po_invoice_stock',
        required=True,
    )
    link_level = fields.Selection(
        LINK_LEVEL_SELECTION,
        string='Synchronization Level',
        default='create_update_cancel',
        required=True,
        help="Create Only: the counterpart document is generated once. "
             "Create and Update: later changes of the source document are "
             "pushed to the counterpart document. Create, Update and Cancel: "
             "cancelling the source document also cancels or flags the "
             "counterpart document.")
    auto_state = fields.Selection(
        [('draft', 'Draft'), ('posted', 'Validated')],
        string='Generated Documents',
        default='draft',
        required=True,
        help="State of the documents generated by this agreement.")
    price_policy = fields.Selection(
        PRICE_POLICY_SELECTION,
        string='Price Policy',
        default='copy',
        required=True,
    )
    markup_percent = fields.Float(string='Markup (%)', default=0.0)
    conflict_policy = fields.Selection(
        CONFLICT_POLICY_SELECTION,
        string='Conflict Policy',
        default='manual',
        required=True,
        help="What to do when both companies modified the same field of the "
             "two linked documents.")
    sync_user_id = fields.Many2one(
        'res.users',
        string='Create Documents As',
        default=SUPERUSER_ID,
        domain=['|', ['active', '=', True], ['id', '=', SUPERUSER_ID]],
        help="User the generated documents are created with.")
    warehouse_a_id = fields.Many2one(
        'stock.warehouse', string='Warehouse of Company A',
        domain="[('company_id', '=', company_a_id)]")
    warehouse_b_id = fields.Many2one(
        'stock.warehouse', string='Warehouse of Company B',
        domain="[('company_id', '=', company_b_id)]")
    date_start = fields.Date(string='Start Date')
    date_end = fields.Date(string='End Date')
    note = fields.Html(string='Terms')
    product_map_ids = fields.One2many(
        'sn.intercompany.product.map', 'agreement_id', string='Product Mapping')
    product_map_count = fields.Integer(compute='_compute_product_map_count')
    sync_log_ids = fields.One2many(
        'sn.intercompany.sync.log', 'agreement_id', string='Synchronization Log')
    sync_log_count = fields.Integer(compute='_compute_sync_log_count')
    issue_ids = fields.One2many(
        'sn.intercompany.sync.issue', 'agreement_id', string='Synchronization Issues')
    issue_count = fields.Integer(compute='_compute_issue_count')
    open_issue_count = fields.Integer(compute='_compute_issue_count')

    _agreement_company_pair_uniq = models.Constraint(
        'UNIQUE(company_a_id, company_b_id)',
        'An agreement already exists between these two companies.',
    )

    @api.depends('product_map_ids')
    def _compute_product_map_count(self):
        for agreement in self:
            agreement.product_map_count = len(agreement.product_map_ids)

    @api.depends('sync_log_ids')
    def _compute_sync_log_count(self):
        for agreement in self:
            agreement.sync_log_count = len(agreement.sync_log_ids)

    @api.depends('issue_ids.state')
    def _compute_issue_count(self):
        for agreement in self:
            agreement.issue_count = len(agreement.issue_ids)
            agreement.open_issue_count = len(
                agreement.issue_ids.filtered(lambda issue: issue.state == 'open'))

    @api.constrains('company_a_id', 'company_b_id')
    def _check_companies(self):
        for agreement in self:
            if agreement.company_a_id == agreement.company_b_id:
                raise ValidationError(_(
                    "An agreement needs two different companies."))
            if agreement.company_a_id.id > agreement.company_b_id.id:
                raise ValidationError(_(
                    "Company A must be the company with the lowest id."))

    @api.constrains('date_start', 'date_end')
    def _check_dates(self):
        for agreement in self:
            if agreement.date_start and agreement.date_end \
                    and agreement.date_start > agreement.date_end:
                raise ValidationError(_(
                    "The end date of %(agreement)s cannot precede its start "
                    "date.", agreement=agreement.display_name))

    @api.constrains('markup_percent')
    def _check_markup(self):
        for agreement in self:
            if agreement.markup_percent < -100:
                raise ValidationError(_(
                    "The markup of %(agreement)s cannot be lower than -100%%.",
                    agreement=agreement.display_name))

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            company_a = vals.get('company_a_id')
            company_b = vals.get('company_b_id')
            if company_a and company_b and company_a > company_b:
                vals['company_a_id'], vals['company_b_id'] = company_b, company_a
                vals['a_sells_to_b'] = vals.get('b_sells_to_a', True)
                vals['b_sells_to_a'] = vals.get('a_sells_to_b', True)
        return super().create(vals_list)

    def write(self, vals):
        if 'company_a_id' in vals or 'company_b_id' in vals:
            vals = dict(vals)
            company_a = vals.get('company_a_id', self.company_a_id.id)
            company_b = vals.get('company_b_id', self.company_b_id.id)
            if company_a and company_b and company_a > company_b:
                vals['company_a_id'], vals['company_b_id'] = company_b, company_a
                a_sells = vals.get('a_sells_to_b', self.a_sells_to_b)
                b_sells = vals.get('b_sells_to_a', self.b_sells_to_a)
                vals['a_sells_to_b'], vals['b_sells_to_a'] = b_sells, a_sells
        return super().write(vals)

    # ------------------------------------------------------------------
    # Direction resolution
    # ------------------------------------------------------------------
    @api.model
    def _find_running(self, company, counterpart):
        """Running agreement covering the two companies, if any."""
        if not company or not counterpart or company == counterpart:
            return self.env['sn.intercompany.agreement']
        return self.sudo().search([
            ('state', '=', 'running'),
            ('active', '=', True),
            ('company_a_id', 'in', (company.id, counterpart.id)),
            ('company_b_id', 'in', (company.id, counterpart.id)),
        ], limit=1)

    def _direction_from(self, company):
        """Direction in which ``company`` sells inside this agreement."""
        self.ensure_one()
        if company == self.company_a_id:
            return 'a_to_b'
        if company == self.company_b_id:
            return 'b_to_a'
        return False

    def _is_direction_enabled(self, direction):
        self.ensure_one()
        return bool(self.a_sells_to_b if direction == 'a_to_b' else self.b_sells_to_a)

    def _source_company(self, direction):
        self.ensure_one()
        return self.company_a_id if direction == 'a_to_b' else self.company_b_id

    def _target_company(self, direction):
        self.ensure_one()
        return self.company_b_id if direction == 'a_to_b' else self.company_a_id

    def _warehouse_for(self, company):
        self.ensure_one()
        return self.warehouse_a_id if company == self.company_a_id else self.warehouse_b_id

    def _valid_today(self):
        self.ensure_one()
        today = fields.Date.context_today(self)
        return (not self.date_start or today >= self.date_start) \
            and (not self.date_end or today <= self.date_end)

    def _covers(self, target_model):
        """Whether the documents of ``target_model`` are in the scope."""
        self.ensure_one()
        if target_model in ('sale.order', 'purchase.order'):
            return True
        if target_model == 'account.move':
            return self.doc_scope in ('so_po_invoice', 'so_po_invoice_stock')
        if target_model == 'stock.picking':
            return self.doc_scope == 'so_po_invoice_stock'
        return False

    # ------------------------------------------------------------------
    # Products and prices
    # ------------------------------------------------------------------
    def _map_product(self, product, direction):
        """Product usable in the target company for ``product``.

        An empty record set means the source product cannot exist in the
        target company: the line is copied as a text line instead.
        """
        self.ensure_one()
        if not product:
            return self.env['product.product']
        mapping = self.product_map_ids.filtered(
            lambda line: line.active
            and line.direction in (direction, 'both')
            and line.source_product_tmpl_id == product.product_tmpl_id)
        if not mapping:
            return self.env['product.product']
        return mapping[:1]._mapped_product()

    def _price_for(self, product, unit_price, target_company):
        """Unit price of the generated line, following the price policy."""
        self.ensure_one()
        if self.price_policy == 'cost_markup' and product:
            cost = product.with_company(target_company).standard_price
            return cost * (1 + self.markup_percent / 100.0)
        return unit_price

    # ------------------------------------------------------------------
    # Consistency check
    # ------------------------------------------------------------------
    @api.model
    def _cron_check_consistency(self):
        agreements = self.search([('state', '=', 'running'), ('active', '=', True)])
        for agreement in agreements:
            agreement._check_consistency()

    def _check_consistency(self):
        """Flag the linked documents that no longer tell the same story."""
        self.ensure_one()
        sale_orders = self.env['sale.order'].sudo().search([
            ('intercompany_agreement_id', '=', self.id),
            ('auto_generated', '=', False),
        ])
        for order in sale_orders:
            self._check_order_pair(order, order._sn_counterpart())
        purchase_orders = self.env['purchase.order'].sudo().search([
            ('intercompany_agreement_id', '=', self.id),
            ('auto_generated', '=', False),
        ])
        for order in purchase_orders:
            self._check_order_pair(order, order._sn_counterpart())

    def _check_order_pair(self, source, counterpart):
        if not counterpart:
            if source.state != 'cancel':
                empty_target = self.env['purchase.order'] if source._name == 'sale.order' \
                    else self.env['sale.order']
                self._raise_issue(
                    'missing',
                    source,
                    empty_target,
                    _("No counterpart document exists for %(source)s.",
                      source=source.display_name),
                )
            return
        if source.state == 'cancel' and counterpart.state not in ('cancel',):
            counterpart._sn_mark_state(
                'diverged',
                _("%(counterpart)s is still open while %(source)s was cancelled.",
                  counterpart=counterpart.display_name, source=source.display_name),
            )
            self._raise_issue(
                'state',
                source,
                counterpart,
                _("Cancelled document %(source)s still has an open counterpart "
                  "%(counterpart)s.",
                  source=source.display_name, counterpart=counterpart.display_name),
            )
            return
        if counterpart.state == 'draft' and not counterpart._sn_quantities_match(source):
            counterpart._sn_mark_state(
                'diverged',
                _("Quantities differ from %(source)s.",
                  source=source.display_name),
            )
            self._raise_issue(
                'diverged',
                source,
                counterpart,
                _("The quantities of %(counterpart)s differ from %(source)s.",
                  counterpart=counterpart.display_name, source=source.display_name),
            )

    def _raise_issue(self, issue_type, source, counterpart, message):
        self.ensure_one()
        Issue = self.env['sn.intercompany.sync.issue'].sudo()
        domain = [
            ('agreement_id', '=', self.id),
            ('source_model', '=', source._name),
            ('source_id', '=', source.id),
            ('issue_type', '=', issue_type),
            ('state', '=', 'open'),
        ]
        if Issue.search_count(domain):
            return Issue.search(domain, limit=1)
        return Issue.create({
            'agreement_id': self.id,
            'issue_type': issue_type,
            'source_model': source._name,
            'source_id': source.id,
            'source_ref': source.display_name,
            'target_model': counterpart._name if counterpart else False,
            'target_id': counterpart.id if counterpart else False,
            'target_ref': counterpart.display_name if counterpart else False,
            'message': message,
        })

    # ------------------------------------------------------------------
    # Actions
    # ------------------------------------------------------------------
    def action_start(self):
        for agreement in self:
            if not agreement.company_a_id or not agreement.company_b_id:
                raise ValidationError(_("Set both companies first."))
            agreement.state = 'running'
            if agreement.warehouse_a_id or agreement.warehouse_b_id:
                continue
            agreement.warehouse_a_id = self.env['stock.warehouse'].sudo().search(
                [('company_id', '=', agreement.company_a_id.id)], limit=1)
            agreement.warehouse_b_id = self.env['stock.warehouse'].sudo().search(
                [('company_id', '=', agreement.company_b_id.id)], limit=1)

    def action_suspend(self):
        self.write({'state': 'suspended'})

    def action_close(self):
        self.write({'state': 'closed'})

    def action_reset_draft(self):
        self.write({'state': 'draft'})

    def action_view_sync_log(self):
        self.ensure_one()
        return {
            'type': 'ir.actions.act_window',
            'name': _('Synchronization Log'),
            'res_model': 'sn.intercompany.sync.log',
            'view_mode': 'list,form',
            'domain': [('agreement_id', '=', self.id)],
            'context': {'default_agreement_id': self.id},
        }

    def action_view_issues(self):
        self.ensure_one()
        return {
            'type': 'ir.actions.act_window',
            'name': _('Synchronization Issues'),
            'res_model': 'sn.intercompany.sync.issue',
            'view_mode': 'list,form',
            'domain': [('agreement_id', '=', self.id)],
            'context': {'default_agreement_id': self.id},
        }
