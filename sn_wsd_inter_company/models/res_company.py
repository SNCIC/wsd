from odoo import SUPERUSER_ID, api, fields, models


class ResCompany(models.Model):
    """Rules that drive the automatic creation of the documents of the other
    companies: one switch per document family, the user the documents are
    created with, and the accounting and stock defaults of the target
    company."""

    _inherit = 'res.company'

    intercompany_generate_bills_refund = fields.Boolean(
        string='Generate Bills and Refunds',
        help="When another company posts a customer invoice or a customer "
             "credit note with this company as customer, the matching vendor "
             "bill or refund is created in the purchase journal of this "
             "company.")
    intercompany_generate_sales_orders = fields.Boolean(
        string='Generate Sales Orders',
        help="When another company confirms a purchase order with this company "
             "as vendor, the matching sales order is created in this company.")
    intercompany_generate_purchase_orders = fields.Boolean(
        string='Generate Purchase Orders',
        help="When another company confirms a sales order with this company as "
             "customer, the matching purchase order is created in this "
             "company.")
    intercompany_document_state = fields.Selection(
        selection=[
            ('draft', 'Draft'),
            ('posted', 'Validated'),
        ],
        string='Automation',
        default='draft',
        help="State of the documents generated by the inter-company rules.")
    intercompany_purchase_journal_id = fields.Many2one(
        comodel_name='account.journal',
        string='Purchase Journal',
        domain='[("type", "=", "purchase")]',
        compute='_compute_intercompany_purchase_journal_id',
        store=True,
        readonly=False,
        help="Purchase journal of the vendor bills generated by the "
             "inter-company rules.")
    intercompany_user_id = fields.Many2one(
        comodel_name='res.users',
        string='Create as',
        default=SUPERUSER_ID,
        domain=['|', ['active', '=', True], ['id', '=', SUPERUSER_ID]],
        help="Responsible user for the creation of the documents triggered by "
             "the inter-company rules.")
    intercompany_warehouse_id = fields.Many2one(
        comodel_name='stock.warehouse',
        string='Warehouse',
        compute='_compute_intercompany_stock_fields',
        store=True,
        readonly=False,
        help="Warehouse set on the sales orders generated for this company by "
             "the inter-company rules.")
    intercompany_receipt_type_id = fields.Many2one(
        comodel_name='stock.picking.type',
        string='Receipt Operation Type',
        compute='_compute_intercompany_stock_fields',
        store=True,
        readonly=False,
        help="Operation type set on the receipts generated for this company by "
             "the inter-company rules.")
    intercompany_sync_delivery_receipt = fields.Boolean(
        string='Synchronize Deliveries to Receipts',
        default=lambda self: self.env['res.groups']._is_feature_enabled(
            'stock.group_production_lot'),
        help="When the delivery of another company is validated, the matching "
             "receipt of this company is filled with the same quantities, lots "
             "and serial numbers.")

    @api.model
    def _find_company_from_partner(self, partner_id):
        """Company a partner stands for.

        A partner is the counterpart of a company when it is the partner of
        that company or one of its addresses, which is what lets a company
        sell to a specific contact or delivery address of another company.
        """
        if not partner_id:
            return self.env['res.company']
        return self.sudo().search([('partner_id', 'parent_of', partner_id)], limit=1)

    @api.model
    def _intercompany_document_name(self, model_name, company, partner=None):
        """Name of a document the inter-company rules create in ``company``.

        A coding rule matching the target company wins, so the generated
        documents follow the numbering configured for that company instead of
        the numbering of the company the user works in. The native sequence of
        the document model is the fallback.
        """
        if 'sn.code.rule' in self.env:
            candidate = self.env[model_name].with_company(company).new({
                'company_id': company.id,
                'partner_id': partner.id if partner else False,
            })
            rule = self.env['sn.code.rule'].sudo().with_company(company)._find_rule(candidate)
            if rule:
                return rule.with_company(company).render(candidate)
        sequence = self.env['ir.sequence'].with_company(company).sudo().next_by_code(model_name)
        return sequence or '/'

    @api.depends('chart_template')
    def _compute_intercompany_purchase_journal_id(self):
        journals_by_company = dict(self.env['account.journal']._read_group(
            domain=[('type', '=', 'purchase')],
            groupby=['company_id'],
            aggregates=['id:recordset'],
        ))
        for company in self:
            if not company.intercompany_purchase_journal_id:
                company.intercompany_purchase_journal_id = journals_by_company.get(company, [False])[0]

    @api.depends('intercompany_generate_sales_orders', 'intercompany_generate_purchase_orders')
    def _compute_intercompany_stock_fields(self):
        warehouses_by_company = dict(self.env['stock.warehouse']._read_group(
            domain=[],
            groupby=['company_id'],
            aggregates=['id:recordset'],
        ))
        receipt_types_by_company = dict(self.env['stock.picking.type']._read_group(
            domain=[('code', '=', 'incoming')],
            groupby=['company_id'],
            aggregates=['id:recordset'],
        ))
        for company in self:
            if not (company.intercompany_generate_sales_orders or company.intercompany_generate_purchase_orders):
                company.intercompany_warehouse_id = False
                company.intercompany_receipt_type_id = False
                continue
            if not company.intercompany_warehouse_id:
                company.intercompany_warehouse_id = warehouses_by_company.get(company, [False])[0]
            if not company.intercompany_receipt_type_id:
                company.intercompany_receipt_type_id = receipt_types_by_company.get(company, [False])[0]
